-- One partition per UTC month of `at` (epoch seconds), named `<table>_yYYYYmMM`.
-- Startup makes the current and next months; the retention job (rollout step 5)
-- will roll and drop them daily.
CREATE FUNCTION ensure_month_partitions(parent text, first_month date, last_month date)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
  month date := date_trunc('month', first_month)::date;
  made integer := 0;
  name text;
BEGIN
  IF parent NOT IN ('section_history', 'history') THEN
    RAISE EXCEPTION 'not a partitioned history table: %', parent;
  END IF;
  WHILE month <= last_month LOOP
    name := format('%s_y%sm%s', parent, to_char(month, 'YYYY'), to_char(month, 'MM'));
    IF to_regclass(name) IS NULL THEN
      EXECUTE format(
        'CREATE TABLE %I PARTITION OF %I FOR VALUES FROM (%s) TO (%s)',
        name,
        parent,
        extract(epoch FROM month::timestamp AT TIME ZONE 'UTC')::bigint,
        extract(epoch FROM (month + interval '1 month')::timestamp AT TIME ZONE 'UTC')::bigint
      );
      made := made + 1;
    END IF;
    month := (month + interval '1 month')::date;
  END LOOP;
  RETURN made;
END;
$$;

-- The Server started storing history in 2026 (0.6); 2025 covers clock skew.
SELECT ensure_month_partitions(t, date '2025-01-01', (now() AT TIME ZONE 'UTC')::date + 62)
FROM (VALUES ('section_history'), ('history')) AS tables (t);
