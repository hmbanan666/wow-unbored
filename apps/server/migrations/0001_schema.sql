-- 0001: today's SQLite tables (ADR 0057), as `data.ts`, `store.ts`,
-- `suggestions.ts` and `blizzard.ts` create them. Times stay bigint epoch
-- seconds; `body_json TEXT` is `body jsonb`, other `*_json` columns are jsonb.
-- Legacy `profiles` and `profile_snapshots` (D57) are not moved.

-- data.ts
CREATE TABLE accounts (
  id text PRIMARY KEY,
  label text NOT NULL,
  first_seen bigint NOT NULL,
  last_seen bigint NOT NULL,
  dropped_json jsonb
);

CREATE TABLE characters (
  id text PRIMARY KEY,
  account_id text NOT NULL,
  name text NOT NULL,
  realm text NOT NULL,
  class text,
  level integer,
  last_seen bigint NOT NULL,
  saved_at bigint,
  dropped_json jsonb,
  device_id text
);
CREATE INDEX characters_account ON characters (account_id);

CREATE TABLE sections_latest (
  owner_kind text NOT NULL,
  owner_id text NOT NULL,
  section text NOT NULL,
  v integer NOT NULL,
  hash text NOT NULL,
  at bigint,
  saved_at bigint,
  updated_at bigint NOT NULL,
  src text,
  unknown integer NOT NULL DEFAULT 0,
  bytes integer NOT NULL,
  body jsonb NOT NULL,
  PRIMARY KEY (owner_kind, owner_id, section)
);
-- Only the Sections the Server reads inside.
CREATE INDEX sections_latest_body ON sections_latest USING gin (body jsonb_path_ops)
  WHERE section IN ('collections', 'reputation');

CREATE TABLE section_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  owner_kind text NOT NULL,
  owner_id text NOT NULL,
  section text NOT NULL,
  at bigint NOT NULL,
  saved_at bigint,
  hash text NOT NULL,
  kind text NOT NULL,
  body jsonb NOT NULL,
  PRIMARY KEY (id, at)
) PARTITION BY RANGE (at);
CREATE INDEX section_history_owner ON section_history (owner_kind, owner_id, at);

CREATE TABLE data_meta (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE addon_errors (
  hash text NOT NULL,
  account text NOT NULL,
  device_id text,
  character_name text NOT NULL,
  realm text NOT NULL,
  version text NOT NULL,
  "where" text NOT NULL,
  text text NOT NULL,
  stack text NOT NULL,
  count integer NOT NULL,
  first_at bigint NOT NULL,
  last_at bigint NOT NULL,
  seen_at bigint NOT NULL,
  PRIMARY KEY (account, hash)
);
CREATE INDEX addon_errors_last ON addon_errors (last_at);

