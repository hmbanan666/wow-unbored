-- Website catalog and home page (ADR 0073, 0074, 0075).
-- Paths and collections share one versioned table. Topics, Path goals and
-- the owner tools that check ids stay with the Path work; they should
-- reference content.paths.id. Do not add a table per mount, item or NPC:
-- there are no per-object pages.
-- These schemas are not in `public`, so the SQLite transfer does not copy them.

CREATE SCHEMA IF NOT EXISTS content;

CREATE TABLE content.paths (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('path', 'collection')),
  slug text NOT NULL CHECK (
    char_length(slug) BETWEEN 1 AND 80
    AND slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
  ),
  locale text NOT NULL DEFAULT 'en' CHECK (locale IN ('en', 'ru')),
  title text NOT NULL,
  description text NOT NULL,
  tier text CHECK (tier IS NULL OR tier IN ('basic', 'deeper', 'complete')),
  -- The previous tier, by slug, so a new version does not dangle an id.
  prerequisite_slug text CHECK (
    prerequisite_slug IS NULL
    OR (
      char_length(prerequisite_slug) BETWEEN 1 AND 80
      AND prerequisite_slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
    )
  ),
  version integer NOT NULL CHECK (version >= 1),
  status text NOT NULL CHECK (status IN ('draft', 'published')),
  body jsonb NOT NULL DEFAULT '{"blocks":[]}'::jsonb,
  updated_at bigint NOT NULL,
  published_at bigint,
  UNIQUE (kind, slug, locale, version)
);

-- One live row per page. Drafts of the next version can sit beside it.
CREATE UNIQUE INDEX content_paths_published
  ON content.paths (kind, slug, locale)
  WHERE status = 'published';

CREATE SCHEMA IF NOT EXISTS web;

-- Site pages that are not a Path (the home page and its SEO fields).
CREATE TABLE web.pages (
  slug text NOT NULL CHECK (
    char_length(slug) BETWEEN 1 AND 80
    AND slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
  ),
  locale text NOT NULL CHECK (locale IN ('en', 'ru')),
  title text NOT NULL,
  description text NOT NULL,
  headline text NOT NULL,
  body jsonb NOT NULL,
  updated_at bigint NOT NULL,
  PRIMARY KEY (slug, locale)
);

