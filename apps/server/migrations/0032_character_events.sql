-- ADR 0099: permanent, private history. Source Section timestamps are epoch seconds.
CREATE TABLE character_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game TEXT NOT NULL CHECK (game IN ('retail', 'forever')),
  character_id TEXT NOT NULL REFERENCES characters(id) ON DELETE CASCADE ON UPDATE CASCADE,
  type TEXT NOT NULL CHECK (type IN ('level_up', 'skill_step', 'recipe_learned', 'gold_close', 'gear_change', 'rep_standing')),
  key TEXT NOT NULL,
  at BIGINT NOT NULL,
  from_value TEXT,
  to_value TEXT NOT NULL,
  day BIGINT,
  UNIQUE (character_id, type, key, at),
  CHECK ((type = 'gold_close' AND day IS NOT NULL) OR (type <> 'gold_close' AND day IS NULL))
);
CREATE UNIQUE INDEX character_events_gold_day ON character_events (character_id, day) WHERE type = 'gold_close';
CREATE INDEX character_events_timeline ON character_events (character_id, at DESC, id DESC);
CREATE INDEX character_events_type ON character_events (character_id, type, at DESC, id DESC);

-- PostgreSQL-only permissions: SQLite initialization splits at this marker.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'unbored_web') THEN
    GRANT SELECT ON character_events TO unbored_web;
  END IF;
END $$;
