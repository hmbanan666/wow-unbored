-- 0002: the upload inbox (ADR 0057 rollout step 4). POST /v1/snapshot checks
-- the upload, stores the gzip bytes here and answers 202; the in-process worker
-- claims queued rows (FOR UPDATE SKIP LOCKED) and runs today's ingest.
CREATE TABLE raw_uploads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id text NOT NULL,
  device_id text NOT NULL,
  character_id text NOT NULL,
  -- sha256 of the inflated JSON; one row per Account and body.
  hash text NOT NULL,
  -- 1 when the upload carries questLog or bags (a plan needs them first).
  priority smallint NOT NULL DEFAULT 0,
  body_gz bytea NOT NULL,
  bytes integer NOT NULL,
  received_at bigint NOT NULL,
  state text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued', 'done', 'failed')),
  attempts integer NOT NULL DEFAULT 0,
  -- Not retried before this time (backoff after a failed attempt).
  next_at bigint NOT NULL DEFAULT 0,
  last_error text,
  -- stored, unchanged, stale, unknown when done.
  result jsonb,
  processed_at bigint,
  UNIQUE (account_id, hash)
);
CREATE INDEX raw_uploads_queue ON raw_uploads (priority DESC, received_at, id)
  WHERE state = 'queued';
CREATE INDEX raw_uploads_account_queue ON raw_uploads (account_id, received_at, id)
  WHERE state = 'queued';
CREATE INDEX raw_uploads_failed ON raw_uploads (processed_at DESC) WHERE state = 'failed';
CREATE INDEX raw_uploads_device ON raw_uploads (device_id);
