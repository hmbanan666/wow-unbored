-- Exports the addon's curated ids (addon/Data) to packages/contracts/catalog/catalog.json,
-- the one catalog the Server's Suggestion rules read (docs/adr/0040).
--   lua5.1 scripts/export-catalog.lua          print the JSON
--   lua5.1 scripts/export-catalog.lua --write  update the file
-- A test compares the file with the output, so run --write after editing addon/Data.

local root = (arg and arg[0] or ""):match("^(.*)/scripts/[^/]+$") or "."
local FILES = { "Holidays", "FunAchievements", "Exploration", "Rares", "Farm" }

local ns = { Data = {} }
for _, name in ipairs(FILES) do
  local chunk = assert(loadfile(root .. "/addon/Data/" .. name .. ".lua"))
  chunk("Unbored", ns)
end

local function sortedKeys(value)
  local keys = {}
  for key in pairs(value) do
    keys[#keys + 1] = key
  end
  table.sort(keys, function(a, b)
    return tostring(a) < tostring(b)
  end)
  return keys
end

local function isArray(value)
  local count = 0
  for _ in pairs(value) do
    count = count + 1
  end
  return count == #value
end

local function quote(text)
  return '"' .. text:gsub('[%c"\\]', function(c)
    local named = { ['"'] = '\\"', ["\\"] = "\\\\", ["\n"] = "\\n", ["\t"] = "\\t" }
    return named[c] or string.format("\\u%04x", c:byte())
  end) .. '"'
end

local function encode(value, indent)
  local kind = type(value)
  if kind == "string" then
    return quote(value)
  elseif kind == "number" then
    if value == math.floor(value) then
      return string.format("%d", value)
    end
    return (string.format("%.6g", value))
  elseif kind == "boolean" then
    return tostring(value)
  elseif kind ~= "table" then
    error("cannot export a " .. kind)
  end
  local inner = indent .. "  "
  local parts = {}
  if isArray(value) then
    if #value == 0 then
      return "[]"
    end
    local flat = true
    for i = 1, #value do
      flat = flat and type(value[i]) ~= "table"
    end
    for i = 1, #value do
      parts[i] = encode(value[i], inner)
    end
    if flat then
      return "[" .. table.concat(parts, ", ") .. "]"
    end
    return "[\n" .. inner .. table.concat(parts, ",\n" .. inner) .. "\n" .. indent .. "]"
  end
  for _, key in ipairs(sortedKeys(value)) do
    parts[#parts + 1] = quote(tostring(key)) .. ": " .. encode(value[key], inner)
  end
  return "{\n" .. inner .. table.concat(parts, ",\n" .. inner) .. "\n" .. indent .. "}"
end

local catalog = {
  about = "Generated by scripts/export-catalog.lua from addon/Data. Do not edit; edit addon/Data and run it with --write.",
  v = 1,
  holidays = ns.Data.Holidays,
  achievements = ns.Data.FunAchievements,
  exploration = ns.Data.Exploration,
  rares = ns.Data.Rares,
  farm = ns.Data.Farm,
}
local text = encode(catalog, "") .. "\n"

if arg and arg[1] == "--write" then
  local file = assert(io.open(root .. "/packages/contracts/catalog/catalog.json", "w"))
  file:write(text)
  file:close()
else
  io.write(text)
end
